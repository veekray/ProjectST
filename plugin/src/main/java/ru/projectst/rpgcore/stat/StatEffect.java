package ru.projectst.rpgcore.stat;

/**
 * Во что превращается значение стата: рейтинг — в проценты.
 *
 * <p><b>Зачем вообще рейтинг.</b> Стат, который прямо равен проценту, упирается
 * в потолок: сто процентов уклонения — это неуязвимость, сто процентов снижения
 * перезарядки — навык каждый тик. Потолок приходится ставить сверху, и тогда
 * очередной пункт стата молча перестаёт что-либо значить. Рейтинг снимает этот
 * вопрос: процент считается кривой насыщения, которая к потолку стремится, но не
 * доходит до него ни при каком значении.
 *
 * <pre>
 *   процент = cap * рейтинг / (рейтинг + cap)
 * </pre>
 *
 * <p><b>Почему одно число, а не два.</b> У кривой мог бы быть отдельный
 * «рейтинг, дающий половину», но тогда наклон у нуля зависел бы от двух чисел
 * сразу. Здесь он всегда единичный: первые пункты рейтинга дают примерно столько
 * же процентов, сколько их самих, и дальше отдача плавно падает. Поэтому старые
 * числа контента, писавшиеся как проценты, не пришлось переписывать — в малых
 * значениях они значат почти то же.
 *
 * <p><b>Отрицательный рейтинг линеен.</b> Ниже нуля та же кривая обращается в
 * деление на ноль, а ещё ниже меняет знак и начинает помогать. Поэтому минус
 * считается прямой с тем же наклоном и ограничивается тем же потолком: хуже,
 * чем на cap процентов, не бывает.
 *
 * @param cap     к какому проценту стремится кривая; он же задаёт её форму
 * @param text    что показать игроку. Буква {@code N} заменяется на процент со
 *                знаком — «+29%» или «−12%». Текст лежит в контенте, потому что
 *                это фраза для игрока, а не правило движка
 * @param inverted рейтинг растёт — показанная величина убывает. Нужно защитам:
 *                 рейтинг защиты снижает получаемый урон, и честная фраза про
 *                 него — «−60% получаемого урона». На расчёт боя не влияет:
 *                 {@link #share(double)} всегда возвращает величину самой
 *                 кривой, а знак разворачивается только в тексте
 */
public record StatEffect(double cap, String text, boolean inverted) {

    /** Метка в тексте, на место которой встаёт процент. */
    public static final String MARK = "N";

    public StatEffect {
        if (cap <= 0) {
            throw new IllegalArgumentException("потолок эффекта должен быть больше нуля");
        }
        if (text == null || !text.contains(MARK)) {
            throw new IllegalArgumentException(
                    "в тексте эффекта должна быть буква N — место для процента");
        }
    }

    /** Доля: 0.29 означает двадцать девять процентов. */
    public double share(double rating) {
        return percent(rating) / 100.0;
    }

    /** Процент, в который превращается рейтинг. */
    public double percent(double rating) {
        if (rating >= 0) {
            return cap * rating / (rating + cap);
        }
        // Ниже нуля — прямая с тем же наклоном, ограниченная тем же потолком.
        return Math.max(-cap, rating);
    }

    /**
     * Готовая строка для подсказки; пусто — показывать нечего.
     *
     * <p>Пусто при нулевом проценте намеренно: «+0%» не говорит игроку ничего, а
     * занимает строку, в которую он смотрит.
     */
    public String note(double rating) {
        long shown = Math.round(percent(rating));
        if (shown == 0) {
            return "";
        }
        long signed = inverted ? -shown : shown;
        // Знак свой, а процент — из фразы: «N% урона» уже несёт знак процента, и
        // добавлять его здесь значило бы «+50%% урона».
        //
        // Минус обычным дефисом, а не типографским: шрифт Minecraft знает не
        // каждый символ, а неизвестный он рисует белым квадратом.
        String number = (signed > 0 ? "+" : "-") + Math.abs(signed);
        return text.replace(MARK, number);
    }
}
