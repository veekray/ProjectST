package ru.projectst.rpgcore.stat;

/**
 * Как надбавка участвует в расчёте.
 *
 * <p>Порядок применения зафиксирован в {@link StatEngine} и нарушаться не может:
 * сначала все FLAT, затем сумма PERCENT, затем произведение MULT. Именно
 * неопределённость этого порядка в старом стеке давала «плюс двадцать процентов,
 * а урон не изменился».
 */
public enum StatOp {

    /** Плоская прибавка к значению. */
    FLAT,

    /** Прибавка в процентных пунктах: 25 означает +25%. Все PERCENT суммируются. */
    PERCENT,

    /** Множитель: 1.5 означает ×1.5. Все MULT перемножаются. */
    MULT
}
