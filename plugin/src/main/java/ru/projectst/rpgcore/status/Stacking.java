package ru.projectst.rpgcore.status;

/**
 * Что происходит при повторном наложении уже активного статуса.
 *
 * <p>Поведение объявляется самим статусом, а не угадывается на месте
 * наложения. В старом стеке это было источником постоянных сюрпризов: один и
 * тот же повторный каст то продлевал эффект, то нет, в зависимости от того,
 * какая механика его ставила.
 */
public enum Stacking {

    /** Повторное наложение игнорируется, активный остаётся как есть. */
    NONE,

    /** Длительность сбрасывается на новую. */
    REFRESH,

    /** Новая длительность прибавляется к остатку. */
    EXTEND,

    /** Добавляется стак, пока не достигнут максимум; длительность обновляется. */
    STACKS
}
