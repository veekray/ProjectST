package ru.projectst.rpgcore.status;

/**
 * Метки статусов, которые читает движок.
 *
 * <p>Собраны здесь по той же причине, по которой собраны идентификаторы статов:
 * пока метка была строкой по месту использования, одно и то же слово жило в двух
 * файлах, и достаточно было опечатки в одном, чтобы «нельзя кастовать»
 * проверялось не там, где накладывается.
 *
 * <p>Что метка значит, решает контент: статус с меткой {@code immobilize} не
 * ходит, потому что так написано здесь, а не потому, что он называется
 * «корнями». Поэтому новый контроль получает поведение строкой в файле, а не
 * правкой Java.
 */
public final class StatusTags {

    /** Пока такой статус держится, цель не применяет навыки. */
    public static final String BLOCKS_CAST = "blocks-cast";

    /**
     * Пока такой статус держится, цель не перемещается.
     *
     * <p>Читается в двух местах, и оба обязательны. Первое — ванильная
     * обездвиженность: цель не ходит. Второе — ворота каста: навык, который
     * двигает кастера, под такой меткой не применяется. Без второго рывок с
     * тремя зарядами был бы бесплатным снятием корней, и корни перестали бы
     * что-либо значить.
     */
    public static final String IMMOBILIZE = "immobilize";

    private StatusTags() {
    }
}
