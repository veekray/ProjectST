package ru.projectst.rpgcore.status;

/**
 * Категория статуса. Определяет, как статус участвует в конвейере урона и в
 * правилах исключительности.
 */
public enum StatusCategory {

    /** Лишает цель действий: стан, корни, изъятие из боя. */
    CONTROL,

    /** Улучшает цель. */
    BUFF,

    /** Ухудшает цель. */
    DEBUFF,

    /** Поглощает урон. Запас берётся из amount активного статуса. */
    SHIELD,

    /** Отменяет урон целиком. */
    IMMUNITY,

    /** Метка: сама ничего не делает, её читают другие навыки. */
    MARK
}
