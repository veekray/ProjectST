package ru.projectst.rpgcore.item;

import java.util.Locale;

/**
 * Где предмет должен находиться, чтобы его статы считались.
 *
 * <p>Слот объявлен у предмета, а не угадывается по материалу. В прежнем стеке
 * тип предмета определял и слот, и поведение, из-за чего «кольцо» приходилось
 * выдавать за шлем, чтобы оно вообще что-то давало.
 */
public enum ItemSlot {

    /** В основной руке. */
    HAND("оружие в руке"),
    /** В левой руке. */
    OFFHAND("вторая рука"),
    HELMET("шлем"),
    CHEST("нагрудник"),
    LEGS("поножи"),
    BOOTS("сапоги"),
    /**
     * Слот артефакта: отдельные ячейки в окне снаряжения, не в инвентаре.
     *
     * <p>Нужен тому, что надевать некуда. Печать, реликвия — всё это в
     * ванильной броне не живёт, а статы давать должно. Ячейки свои, поэтому
     * артефакт не занимает руку и не мешает носить щит.
     */
    ARTIFACT("артефакт"),
    /**
     * Кольцо: идёт в любую из двух ячеек колец.
     *
     * <p>Слот один на оба пальца, а не «левое» и «правое». Иначе одно и то же
     * кольцо пришлось бы объявлять дважды, и второе надеть было бы нельзя
     * только потому, что его файл назван не той рукой.
     */
    RING("кольцо"),
    AMULET("амулет"),
    BRACELET("браслет"),
    /**
     * Перчатки — своя ячейка, а не ванильная броня: в Minecraft рук у брони
     * нет, и надетые перчатки жили бы только в данных игрока.
     */
    GLOVES("перчатки"),

    /**
     * Любой слот, где предмет считается надетым.
     *
     * <p>То есть ванильные плюс ячейки снаряжения. Не «где угодно в
     * инвентаре»: предмет, дающий статы из рюкзака, превратил бы инвентарь в
     * список надбавок, и понять, откуда у игрока числа, стало бы нельзя.
     */
    ANY("любой слот");

    private final String title;

    ItemSlot(String title) {
        this.title = title;
    }

    public String key() {
        return name().toLowerCase(Locale.ROOT);
    }

    /** Имя слота для отказа словами: «это не кольцо, а шлем». */
    public String title() {
        return title;
    }
}
