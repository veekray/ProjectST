package ru.projectst.rpgcore.item;

/**
 * Что запускает умение предмета.
 *
 * <p>Набор закрытый и соответствует тому, о чём сервер действительно узнаёт от
 * ванильного клиента. В старом стеке режимов было больше десятка, часть из них
 * не работала вовсе, и отличить неработающий режим от неверно настроенного
 * предмета было нельзя.
 */
public enum ItemTrigger {

    /** Правый щелчок предметом в руке. */
    RIGHT_CLICK,
    /** Левый щелчок предметом в руке. */
    LEFT_CLICK,
    /** Правый щелчок с зажатым Shift. */
    SNEAK_RIGHT_CLICK,
    /** Удар по цели этим предметом. */
    ON_HIT
}
