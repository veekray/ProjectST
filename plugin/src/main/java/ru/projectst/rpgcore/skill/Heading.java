package ru.projectst.rpgcore.skill;

/**
 * Направление по земле: куда двигаться, если не туда, куда смотришь.
 *
 * <p>Нужно рывку. Рывок по взгляду и рывок по ходу — разные вещи: игрок,
 * который бежит влево и смотрит на врага, нажимая рывок, хочет уйти влево, а не
 * прыгнуть на врага. Поэтому направление приходит отдельно от поворота головы, и
 * его нельзя забыть задать молча: {@code null} означает «направления нет»,
 * и тогда рывок честно идёт по взгляду.
 *
 * <p>Длина всегда единичная: нормализация в конструкторе, а не у вызывающего.
 * Иначе «сила рывка» зависела бы от того, держит игрок одну клавишу или две —
 * по диагонали вектор длиннее, и рывок вбок-вперёд унёс бы дальше, чем вперёд.
 *
 * @param x доля по X
 * @param z доля по Z
 */
public record Heading(double x, double z) {

    /** Короче этого вектор считается нулевым: он не задаёт никакого направления. */
    public static final double MIN_LENGTH = 1.0e-4;

    public Heading {
        double length = Math.sqrt(x * x + z * z);
        if (!Double.isFinite(length) || length < MIN_LENGTH) {
            throw new IllegalArgumentException("направление без длины: " + x + ", " + z);
        }
        x /= length;
        z /= length;
    }

    /**
     * Направление или {@code null}, если его нет.
     *
     * <p>Нуль здесь — обычное дело, а не ошибка: игрок, стоящий на месте,
     * никуда не идёт. Поэтому отсутствие направления возвращается значением, а
     * не исключением, и обрабатывается там, где решают, чем его заменить.
     */
    public static Heading orNull(double x, double z) {
        double length = Math.sqrt(x * x + z * z);
        if (!Double.isFinite(length) || length < MIN_LENGTH) {
            return null;
        }
        return new Heading(x, z);
    }
}
