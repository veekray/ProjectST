package ru.projectst.rpgcore.skill;

/**
 * Что запускает навык.
 *
 * <p>Написано в самом навыке, одним ключом. В старом стеке триггер жил в чужом
 * файле: тело навыка в одном месте, строка {@code ~onDamaged} — в другом, и
 * узнать, срабатывает ли навык вообще, можно было только найдя оба.
 *
 * <p>Набор закрытый. Новый триггер добавляется сюда и в слушатель событий, то
 * есть компилятором: строка в конфиге, которая ничего не запускает, —
 * невозможна.
 */
public enum SkillTrigger {

    /** Игрок применяет сам: кнопкой или командой. */
    MANUAL,

    /** По владельцу навыка попали. Триггером становится ударивший. */
    ON_DAMAGED,

    /** Владелец навыка нанёс урон. Триггером становится получивший. */
    ON_DEAL_DAMAGE,

    /** Владелец навыка кого-то убил. Триггером становится убитый. */
    ON_KILL,

    /** Срабатывает сам через равные промежутки: аура, пассивный эффект. */
    ON_INTERVAL;

    /** Пассивный ли это навык: такой нельзя повесить на слот. */
    public boolean passive() {
        return this != MANUAL;
    }
}
