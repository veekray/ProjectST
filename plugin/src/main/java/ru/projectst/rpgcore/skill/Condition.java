package ru.projectst.rpgcore.skill;

/**
 * Условие шага.
 *
 * <p>Два важных отличия от того, как это было устроено в старом стеке.
 *
 * <p>Первое: условие явно говорит, <b>кого</b> проверяет — кастера или цель.
 * Там инлайновое {@code ?condition} всегда проверяло кастера, но выглядело
 * так, будто проверяет цель, и на этом терялись часы. Здесь это написано в
 * самом имени поля.
 *
 * <p>Второе: условие цели <b>не отменяет шаг целиком</b>, а отсеивает те цели,
 * которые его не прошли. Отмена всего шага при пустом списке была отдельной
 * ловушкой: метаскилл без подходящих целей не выполнял даже партиклы.
 *
 * @param scope кого проверяем
 * @param check что проверяем
 * @param value аргумент проверки: id статуса, число
 * @param negated отрицание
 */
public record Condition(Scope scope, Check check, String value, boolean negated) {

    public enum Scope {
        /** Проверяется кастер; при провале шаг не выполняется вовсе. */
        CASTER,
        /** Проверяется каждая цель; не прошедшие просто отсеиваются. */
        TARGET
    }

    public enum Check {
        /** На проверяемом есть действующий статус. */
        HAS_STATUS,
        /** У проверяемого столько стаков статуса или больше. */
        STATUS_STACKS,
        /** Проверяемый — игрок. */
        IS_PLAYER,
        /** Срабатывает с заданной вероятностью в процентах. */
        CHANCE,
        /** Проверяемый стоит в зоне с этим тегом; {@code тег:own} — только в своей. */
        IN_ZONE,
        /** Проверяемый стоит минимум в N зонах с этим тегом: {@code тег:N}. */
        ZONE_COUNT
    }

    public Condition {
        if (scope == null || check == null) {
            throw new IllegalArgumentException("у условия обязательны scope и check");
        }
        if (check != Check.IS_PLAYER && (value == null || value.isBlank())) {
            throw new IllegalArgumentException("проверке " + check + " нужен аргумент");
        }
    }
}
