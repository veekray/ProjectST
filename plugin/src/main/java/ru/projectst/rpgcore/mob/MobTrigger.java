package ru.projectst.rpgcore.mob;

/**
 * Что запускает навык моба.
 *
 * <p>Набор закрытый и соответствует тому, о чём сервер действительно узнаёт.
 * Отдельного языка для ИИ нет: моб запускает те же навыки, что игрок, по тем же
 * правилам. В прежнем стеке у мобов был свой набор механик, пересекающийся с
 * игровым процентов на восемьдесят, и расхождения между ними приходилось искать
 * поштучно.
 */
public enum MobTrigger {

    /** Сразу после появления. */
    ON_SPAWN,
    /** Через равные промежутки, пока моб жив. */
    ON_INTERVAL,
    /** По мобу попали; триггером становится ударивший. */
    ON_DAMAGED,
    /** Моб ударил; триггером становится получивший. */
    ON_ATTACK,
    /** Моб умер; триггером становится убивший, если он был. */
    ON_DEATH
}
