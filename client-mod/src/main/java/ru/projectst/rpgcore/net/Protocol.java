package ru.projectst.rpgcore.net;

/**
 * Канал связи с клиентским модом.
 *
 * <p><b>Версия в первом байте каждого сообщения.</b> Не в рукопожатии, не в
 * настройках — в самом сообщении. Иначе клиент старой версии молча читает новый
 * формат и показывает мусор: числа не те, полоса не та, и жалоба приходит как
 * «плагин врёт». Версия в байте даёт обеим сторонам возможность отказаться
 * словами.
 *
 * <p><b>Клиент просит, сервер решает.</b> С версии 2 мод умеет присылать
 * действия: применить слот, изучить навык, вложить очко, занять слот, выбрать
 * класс. Ни одно из них не выполняется «потому что клиент так сказал» — каждое
 * идёт через те же службы, что и команда в чате, со всеми их проверками и
 * отказами. Злонамеренный клиент может попросить ровно то, что игрок может
 * набрать руками, и получит тот же ответ.
 *
 * <p><b>Мод обязателен</b>: без рукопожатия игрока не пускают на сервер
 * (ModGate). Но правила всё равно живут только на сервере. Канал — способ
 * показать и попросить, а не способ что-то сделать: меню открывается и
 * командой, навык применяется и через {@code /rpg slot}, и игрок, оставшийся
 * без мода, теряет удобство, а не возможности.
 */
public final class Protocol {

    /**
     * Версия формата.
     *
     * <p>2 — счётчики ядра класса, данные меню и действия от клиента.
     * <p>3 — описание навыка и наибольший урон за попадание: подсказке в меню
     * нужно и то, и другое, а выводить их на клиенте значило бы считать баланс
     * второй раз.
     * <p>4 — пояснение к стату: во что превращается рейтинг защиты.
     * <p>5 — выносливость, заряды врождённого рывка и ввод движения от клиента.
     * <p>6 — ячейки артефактов: что в них лежит и просьбы положить и забрать.
     * <p>7 — окно снаряжения: тринадцать ячеек вместо ряда артефактов. Вещи
     * переносит ванильный контейнер, поэтому просьбы «положить» и «забрать»
     * ушли, а вместо карточек артефактов приходят только отказы — чем ячейка
     * не действует.
     * <p>8 — бафы и дебафы значками: у статуса полный срок, короткое описание и
     * то, что он даёт статам, готовыми числами.
     * <p>9 — канал эффектов {@link #CHANNEL_FX}: границы областей, зоны, снаряды,
     * следы и вспышки крита, всё с посчитанными сервером радиусами и сроками.
     * <p>10 — подготовка каста и предупреждение удара, статусы на любых
     * существах (корни на ногах цели держатся ровно столько, сколько висит
     * статус), звуки мода, источник у вспышки, владелец у зоны и ударивший у
     * попадания.
     */
    public static final int VERSION = 10;

    /**
     * Ключ заголовка окна снаряжения.
     *
     * <p>По нему мод узнаёт контейнер и рисует его своим экраном. Ключ, а не
     * текст: текст правят, и окно, узнаваемое по тексту, однажды перестало бы
     * узнаваться — без единой ошибки, просто сундуком.
     */
    public static final String GEAR_TITLE = "rpgcore.gear.title";

    /**
     * Ячейки окна снаряжения по порядку: номер в списке — номер ячейки
     * контейнера.
     *
     * <p>Список здесь, а не только в моде и не только в плагине: это договор
     * двух сторон о том, какая ячейка шлем, а какая кольцо. Разойдись они —
     * и кольцо надевалось бы в шлем.
     */
    public static final java.util.List<String> GEAR_CELLS = java.util.List.of(
            "helmet", "chest", "legs", "boots", "offhand",
            "ring_left", "ring_right", "amulet", "bracelet", "gloves",
            "artifact_1", "artifact_2", "artifact_3");

    /**
     * Размер контейнера снаряжения: два ряда по девять.
     *
     * <p>Ванильный контейнер бывает только рядами по девять, а ячеек тринадцать.
     * Лишние пять существуют, но не рисуются и ничего не принимают.
     */
    public static final int GEAR_SIZE = 18;

    /** Клиент говорит, что он есть, и называет свою версию формата. */
    public static final String CHANNEL_HELLO = "rpgcore:hello";

    /** Сервер отвечает на рукопожатие: принято или отказано. */
    public static final String CHANNEL_WELCOME = "rpgcore:welcome";

    /** Сервер присылает состояние игрока. */
    public static final String CHANNEL_STATE = "rpgcore:state";

    /** Сервер присылает всё, что нужно меню: классы, навыки, числа. */
    public static final String CHANNEL_MENU = "rpgcore:menu";

    /**
     * Сервер присылает видимые события навыков.
     *
     * <p>Только тем, кто поздоровался, и только о том, что рядом. Игрок без мода
     * вместо событий видит ванильные частицы из тех же навыков — и никогда оба
     * вида сразу.
     */
    public static final String CHANNEL_FX = "rpgcore:fx";

    /** Клиент просит действие. */
    public static final String CHANNEL_ACTION = "rpgcore:action";

    /** Исход рукопожатия. */
    public enum Handshake {
        /** Версии совпали, состояние будет приходить. */
        ACCEPTED,
        /** Мод старее сервера: обновить мод. */
        MOD_TOO_OLD,
        /** Мод новее сервера: обновить плагин. */
        MOD_TOO_NEW;

        public int code() {
            return ordinal();
        }

        public static Handshake of(int code) {
            Handshake[] values = values();
            return code >= 0 && code < values.length ? values[code] : MOD_TOO_OLD;
        }
    }

    /**
     * Что просит клиент.
     *
     * <p>Набор закрытый и маленький намеренно: канал, через который можно
     * попросить «что угодно», однажды попросят не то.
     */
    public enum Action {
        /** Применить навык из слота. */
        CAST_SLOT,
        /** Изучить навык. */
        UNLOCK,
        /** Вложить очко в уровень навыка. */
        UPGRADE,
        /** Занять слот навыком. */
        BIND,
        /** Освободить слот. */
        UNBIND,
        /** Выбрать класс. */
        CHOOSE_CLASS,
        /** Прислать данные меню заново. */
        REFRESH_MENU,
        /**
         * Открыть окно снаряжения.
         *
         * <p>Только открыть: вещи по ячейкам переносит ванильный контейнер, и
         * каждый щелчок в нём проверяет сервер. Просьбы «положить вот это» в
         * канале нет — канал, через который можно попросить предмет, однажды
         * попросят не тот.
         */
        OPEN_GEAR,
        /**
         * Применить врождённый рывок.
         *
         * <p>Единственное действие, которое несёт числа: нажатые клавиши
         * движения. Их знает только клиент, и это ровно то, чего сервер знать не
         * может. Направление по ним считает всё равно сервер — по повороту,
         * который видит сам.
         */
        CAST_DASH;

        public int code() {
            return ordinal();
        }

        public static Action of(int code) {
            Action[] values = values();
            return code >= 0 && code < values.length ? values[code] : REFRESH_MENU;
        }
    }

    /** Чем ответить на рукопожатие клиента с этой версией. */
    public static Handshake decide(int clientVersion) {
        if (clientVersion == VERSION) {
            return Handshake.ACCEPTED;
        }
        return clientVersion < VERSION ? Handshake.MOD_TOO_OLD : Handshake.MOD_TOO_NEW;
    }

    private Protocol() {
    }
}
